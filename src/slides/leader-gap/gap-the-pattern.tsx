// THE PATTERN — §6.4, the FOURTH slide of THE GAP, and the slide that turns the three
// failures in front of it into one claim.
//
// Spec §6.4 (content) · §4.3's leader deck table · §11's Phase 7 row. §6.4 is ONE LINE —
// "The pattern across the three failures" — and that is not an oversight in the spec: B.4
// HAS NO CONTENT OF ITS OWN. It is the SHAPE of B.3, which is why the two ship on one
// ticket. B.3 lays down three first-person Nanovest failures; this slide says what all
// three were the same. No #16 prototype covers it, so nothing is productionized from one;
// the visual contract is settled here the way `gap-hardest-part` and `gap-no-sop` settled
// theirs — one figure component (`./components/ThePatternBeats.tsx`), one geometry module
// (`./the-pattern-geometry.ts`), all copy in `./content.ts`.
//
// WHAT THE SLIDE IS FOR, IN ONE SENTENCE: it hands the argument to §6.5's Capability
// Ladder by proving B.1's claim on the presenter's own record. B.1 asserts that the
// hardest part is not the tools — about the world, with somebody else's statistic. B.4
// says the same thing about three failures the presenter owns, and names what was missing
// as a CAPABILITY. That is what makes the ladder the next thing the room wants rather
// than the next thing the deck has.
//
// THE PROVENANCE, AND WHERE THE DECK DEPARTS FROM IT. The HR original drew this pattern
// itself: `docs/researches/2026-07-31-hr-group-agentic-org-analysis.md` slide 8 ("The
// Pattern Emerges" — methodology over tools · research over building · champions over
// labour) and `docs/researches/internal-hr-group.md` §1.4, whose one-line root cause is
// "Tools Without Direction + Tools Without Strategy + Tools Without Empowerment = Noise"
// (§3.3). HR's pattern points at ENABLEMENT — its three shifts are code → knowledge,
// implementors → enablers, build it → enable it. **§6.4's reframe is the deck's own and
// it points at CAPABILITY instead**, because enablement is a description of what the team
// changed and capability is a property the organisation either has or does not. Only the
// second one is a thing a ladder can measure, and without it B.4 is a second telling of
// B.3 with the lesson attached.
//
// THE DELIBERATE ECHO, AND IT IS THE POINT OF THE SLIDE. B.1 (`gapHardestPartContent`)
// headlines "The hardest part is not the tools." and labels its own band "THE GAP · ACCESS
// AGAINST CAPABILITY". This slide's capability line closes that loop on purpose: B.1
// asserted it about the world, B.4 proves it on the record. Recorded as CHOSEN and not
// leaked, exactly as `gapHardestPartContent` records its own "earned" rhyme with the
// ladder. NONE OF B.1'S ACTUAL VOCABULARY IS RE-SPENT — not `procured`, `instantly`,
// `invoice`, `tool access`, `70%`, `30%`, `70/30`, `people & process` or `earned` — and
// the closer says "buying" rather than "procured" for exactly that reason. An echo is a
// second slide reaching the same conclusion by its own route; a re-spend is the first
// slide's sentence arriving late.
//
// WHAT THIS SLIDE MAY NOT SAY:
//   · L1–L5, `rung`, `ladder`, `level`, `decision contract` → §6.5 owns all of it, and
//     this slide hands off to it without pre-spending its nouns. The point of a handoff
//     is that the next slide gets to introduce its own vocabulary.
//   · SHADOW AI, in any of its three passes → §6.2 (condition) / §6.7 (D.3 rational
//     behaviour, D.4 exposure). Nothing here is about tools people reached for unasked.
//   · THE HR p16–18 OUTCOMES §6.3 CUTS — the performance multiple, the chatbot's name and
//     its conversation and deflection figures, the four benchmarked apps, "same codebase",
//     "one large prompt". Outcomes brag and failures transfer; a slide that generalises
//     the failures must not smuggle back the wins the slide in front of it dropped.
//   · A SUCCESSOR, OR A COUNT OF ITS SUCCESSORS. No "the next slide", no "the next four",
//     no letter. The run is composed per deck set (§3.4) and a sentence that pointed at
//     its own successors goes stale the first time one is inserted or cut —
//     `gapHardestPartContent.closer` and `gapNoSopContent.closer` both record the rule and
//     this slide follows it.
//
// NO BRAND AXIS. The third file in this directory and the fourth in the leader tree to
// import no `VARIANT` at all (`gap-hardest-part`, `gap-no-sop` and `mandate-enablement`
// are the others). §4.4's seven brand × deckSet slots do not list this slide, and the
// three failures it generalises are the PRESENTER'S — Nanovest's, first person — so there
// is nothing for a brand to vary: neither leader room owns this record and neither is
// being shown its own evidence. Both rooms read identical bytes.
//
// WHY THE SLIDE IS SHAPED THIS WAY. The stage is a BRACE: three reductions stacked on the
// left, a vertical hairline spanning all three, a short stub leaving that hairline at its
// exact centre, and the one pattern statement to its right, centred against the brace.
// Nothing else in this deck draws a convergence — B.1 draws a horizontal split bar, B.2 a
// lopsided diptych with four empty rules, B.3 a dated ledger with a vertical spine, B.5 a
// staircase — and a brace is the literal shape of "the pattern across the three failures".
// The three reductions are deliberately NOT restatements of B.3's sentences: they are
// parallel `X, with no Y` noun phrases that reduce each failure to its missing half, so
// the room can SEE the three rhyme before the slide says so.
//
// 4 POSES, one argument each:
//   0 — THE THREE, IN ONE LINE EACH. The heading and all three reductions. ALL THREE
//       ARRIVE ON ONE POSE, and that is a rule rather than a convenience: a pattern
//       across three things cannot be argued from one or two, so a pose resting on a
//       partial list would be resting on evidence that does not yet support any
//       generalisation at all.
//   1 — WHAT WAS THE SAME. The heading, then the brace and the statement on ONE step. A
//       brace pointing at nothing is a stray graphic, so both halves of it arrive with the
//       sentence they point at.
//   2 — THE VERDICT. One copper rule closes the brace, and one line names what was
//       missing: not a tooling problem, a capability the organisation did not have.
//   3 — THE CLOSER. Three failures, one absence, and the thing buying could never have
//       closed.
//
// NO POSE RESTS ON EVIDENCE WITH ITS CONCLUSION MISSING — the property the pose map is
// checked against rather than the pose count. Pose 0 rests on a COMPLETE list under a
// heading that says what it is; two of three reductions on a stage is an anecdote with a
// bracket waiting for it. Pose 1's last arrival is the brace WITH the statement, so the
// pose never rests on a pointer aimed at empty space. Pose 2's last arrival is the
// capability line and not the rule above it. Pose 3's last arrival is the closer, which
// frames every band above it.
//
// `canonicalPose: 3` — the fullest pose, and the only one the PDF and PPTX exports print.
// Anything lower would export a page that reduces three of the presenter's own failures to
// three phrases and stops before the sentence that says what the absence was. For this
// slide in particular that is the one way it could travel badly: a page of three admitted
// failures with no verdict attached is a confession somebody else can re-caption, and the
// closer is what turns it back into an argument about capability.
//
// THE LETTER IS NOT AUTHORED HERE. This slide composes as the FOURTH of the `gap` run —
// B.4 in today's leader decks — and every figure behind it in the run steps by one the day
// another lands in front of it (§3.4 R2). Neither number is written down in any file under
// `src/slides/leader-gap/`: `FigLabel` takes a LABEL only and the composer derives the rest
// (§3.5).
